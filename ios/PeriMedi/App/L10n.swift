import Foundation
import SwiftUI

enum AppLanguage: String, CaseIterable, Identifiable {
    case en, de
    var id: String { rawValue }

    var locale: Locale {
        Locale(identifier: self == .de ? "de" : "en")
    }

    static func detectDefault() -> AppLanguage {
        let preferred = Locale.preferredLanguages.joined(separator: ",").lowercased()
        return preferred.contains("de") ? .de : .en
    }
}

@MainActor
final class LocaleController: ObservableObject {
    @AppStorage("perimedi.locale") private var stored: String = ""

    @Published var language: AppLanguage {
        didSet { stored = language.rawValue }
    }

    init() {
        let stored = UserDefaults.standard.string(forKey: "perimedi.locale") ?? ""
        if stored == "de" {
            language = .de
        } else if stored == "en" {
            language = .en
        } else {
            language = AppLanguage.detectDefault()
        }
    }

    func t(_ key: String, _ vars: [String: String] = [:]) -> String {
        var value = L10n.table[language]?[key] ?? L10n.table[.en]?[key] ?? key
        for (k, v) in vars {
            value = value.replacingOccurrences(of: "{{\(k)}}", with: v)
        }
        return value
    }
}

